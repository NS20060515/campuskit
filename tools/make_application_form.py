def by_prefix(prefix):
    for p in paras:
        if p.text.strip().startswith(prefix):
            return p
    raise SystemExit("未找到段落: " + prefix)


def set_text(p, text):
    """保留首个 run 的格式，替换整段文字"""
    for r in p.runs[1:]:
        r._element.getparent().remove(r._element)
    if p.runs:
        p.runs[0].text = text
    else:
        p.add_run(text)


def clone_after(anchor, text):
    """克隆 anchor 的段落格式，插入其后，返回新段落对象"""
    new_el = copy.deepcopy(anchor._p)
    anchor._p.addnext(new_el)
    from docx.text.paragraph import Paragraph
    np = Paragraph(new_el, anchor._parent)
    for r in np.runs[1:]:
        r._element.getparent().remove(r._element)
    if np.runs:
        np.runs[0].text = text
    else:
        np.add_run(text)
    return np


def drop(p):
    p._element.getparent().remove(p._element)


def fill(p, blocks):
    """blocks: [(kind, text)]，kind: body/sub/plain；body 用于首段"""
    first = True
    anchor = p
    for kind, text in blocks:
        if first:
            target = p
            set_text(p, text)          # 必须先写入文字，只设格式会保留模板占位符
            first = False
        else:
            target = clone_after(anchor, text)
            anchor = target
        if kind == "body":
            target.paragraph_format.first_line_indent = Pt(21)   # 2 字符缩进，与模板一致
            target.paragraph_format.space_after = Pt(3)
            target.paragraph_format.line_spacing = 1.5
        elif kind == "sub":
            target.paragraph_format.first_line_indent = Pt(0)
            target.paragraph_format.left_indent = Pt(21)
            target.paragraph_format.space_after = Pt(2)
            target.paragraph_format.line_spacing = 1.45
        else:
            target.paragraph_format.first_line_indent = Pt(0)
            target.paragraph_format.space_after = Pt(2)
            target.paragraph_format.line_spacing = 1.45
    return anchor


def add_figure(anchor, img, caption, width_cm):
    """在 anchor 之后插入一张图与图注"""
    p = clone_after(anchor, "")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Pt(0)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    run = p.runs[0] if p.runs else p.add_run()
    run.text = ""
    run.add_picture(img, width=Cm(width_cm))

    c = clone_after(p, caption)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Pt(0)
    c.paragraph_format.space_after = Pt(8)
    for r in c.runs:
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0x60, 0x60, 0x60)
    return c


